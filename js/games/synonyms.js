/* שפה – נרדפות והפכים. Pick the word with the same meaning – or the opposite one.
   Levels: opposites (1–10) → synonyms (11–20) → mixed, with the opposite planted as a trap (21+).
   Score = 80% correct + 20% speed. */
(function () {
  const ROUNDS = 10;
  // word, synonym, opposite
  const W = [
    ["גדול", "ענק", "קטן"], ["שמח", "עליז", "עצוב"], ["מהיר", "זריז", "איטי"], ["חם", "לוהט", "קר"], ["חזק", "איתן", "חלש"],
    ["יפה", "נאה", "מכוער"], ["עשיר", "אמיד", "עני"], ["חכם", "נבון", "טיפש"], ["ישן", "עתיק", "חדש"], ["רועש", "קולני", "שקט"],
    ["אמיץ", "גיבור", "פחדן"], ["נקי", "מצוחצח", "מלוכלך"], ["קל", "פשוט", "קשה"], ["גבוה", "רם", "נמוך"], ["אור", "תאורה", "חושך"],
    ["להתחיל", "לפתוח", "לסיים"], ["לצחוק", "לגחך", "לבכות"], ["לאהוב", "לחבב", "לשנוא"], ["לזכור", "לשנן", "לשכוח"], ["לבוא", "להגיע", "ללכת"],
    ["רחב", "מרווח", "צר"], ["מלא", "גדוש", "ריק"], ["רטוב", "לח", "יבש"], ["נדיב", "רחב לב", "קמצן"], ["אמת", "כנות", "שקר"],
    ["שלום", "שלווה", "מלחמה"], ["ברור", "מובן", "מעורפל"], ["רך", "עדין", "קשוח"], ["מתוק", "מתקתק", "מר"], ["זקן", "קשיש", "צעיר"],
    ["עייף", "תשוש", "רענן"], ["כועס", "רוגז", "רגוע"], ["לקנות", "לרכוש", "למכור"], ["לשבת", "להתיישב", "לקום"], ["לשאול", "לברר", "לענות"],
    ["קרוב", "סמוך", "רחוק"], ["הרבה", "המון", "מעט"], ["תמיד", "לעולם", "אף פעם"], ["שמן", "עבה", "רזה"], ["ארוך", "ממושך", "קצר"]
  ];
  Games.register({
    id: "synonyms", cat: "language", name: "נרדפות והפכים", icon: "↔️",
    desc: "מילה באותה משמעות – או ההפך",
    how: `מופיעה מילה ושאלה: "מה ההפך?" או "מה המילה הנרדפת?" (אותה משמעות). בחרו את התשובה. ${ROUNDS} שאלות.<br>ברמות 1–10 רק הפכים, ברמות 11–20 רק נרדפות, ומרמה 21 מעורבב – ולפעמים ההפך מופיע בין התשובות כדי לבלבל.`,
    start(stage, level, api) {
      const order = shuffle(W.slice()).slice(0, ROUNDS);
      return runQuiz(stage, api, {
        rounds: ROUNDS, targetT: lerp(5, 8, level), accW: 80, optClass: "txt",
        make(i) {
          const w = order[i - 1];
          const mode = level <= 10 ? "opp" : level <= 20 ? "syn" : pick(["opp", "syn"]);
          const ans = mode === "opp" ? w[2] : w[1];
          const trap = level >= 21 ? (mode === "opp" ? w[1] : w[2]) : null;
          const pool = W.filter((x) => x !== w).flatMap((x) => [x[1], x[2]]);
          const others = shuffle(pool).slice(0, trap ? 2 : 3);
          if (trap) others.push(trap);
          const q = mode === "opp" ? "מה ההפך של" : "מה המילה הנרדפת ל";
          return { html: `<div class="q-line">${q}</div><div class="big-q">${w[0]}</div>`, ans, opts: shuffle([ans, ...others]), prompt: mode === "opp" ? "⇄ הפך" : "＝ אותה משמעות" };
        }
      });
    }
  });
})();
