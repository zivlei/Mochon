/* שפה – נרדפות והפכים. Pick the word with the same meaning – or the opposite one.
   Levels: always mixed, with the other meaning as a trap: rich everyday words → literary words.
   Score = 80% correct + 20% speed. */
(function () {
  const ROUNDS = 10;
  // word | same meaning | opposite | two related words that are neither
  const EVERYDAY = `נדיב|רחב לב|קמצן|עשיר|אהוב
חרוץ|שקדן|עצלן|מוכשר|מסודר
צנוע|עניו|יהיר|ביישן|פשוט
נחוש|החלטי|הססן|כועס|חזק
ערמומי|נכלולי|תמים|זהיר|מצחיק
אדיש|שווה נפש|נלהב|עייף|שקט
ארעי|זמני|קבוע|מוקדם|קצר
נדיר|יוצא דופן|שכיח|יפה|עתיק
מעורפל|עמום|ברור|אפור|רחוק
עקשן|קשה עורף|ותרן|גאה|צודק
גדוש|מלא|ריק|כבד|רחב
אמיד|בעל אמצעים|עני|נדיב|חשוב
נינוח|רגוע|מתוח|איטי|נחמד
לסרב|למאן|להסכים|לשאול|להתלבט
להסתיר|להצניע|לחשוף|לאבד|לשמור
לשבח|להלל|לגנות|לתאר|לסלוח
להרחיב|להגדיל|לצמצם|לפזר|לבנות
לזרז|להחיש|לעכב|לחפש|להוביל
לבטוח|לסמוך|לחשוד|לשמור|לקוות
להתיר|להרשות|לאסור|להזהיר|לבקש
שלווה|רוגע|סערה|שמחה|בדידות
מחסור|חוסר|שפע|בזבוז|חיסכון
אומץ|תעוזה|פחדנות|כוח|ניצחון`;
  const LITERARY = `נבער|בור|מלומד|נרגש|תמים
שחוח|כפוף|זקוף|עצוב|נמוך
זחוח|יהיר|עניו|שמח|שבע
חפוז|נמהר|מתון|קצר|חרוץ
כחוש|צנום|בריא בשר|חיוור|קטן
צלול|זך|עכור|רטוב|עמוק
איתן|יציב|רופף|גבוה|עתיק
נרגן|רטנן|מרוצה|נרדם|מבוהל
מהוגן|הגון|נבזי|אמיד|מנומס
שגור|רגיל|נדיר|מהיר|סגור
רחום|רחמן|אכזרי|אהוב|חולה
קדום|עתיק|חדיש|יקר|מזרחי
לצדד|לתמוך|להתנגד|להסתכל|להמתין
לקמץ|לחסוך|לבזבז|לספור|לאסוף
להכחיש|לכפור|להודות|לשכוח|לכעוס
להתייגע|להתעייף|לנוח|להתרגז|להצליח
לנטוש|לעזוב|לדבוק|לחפש|לברוח
יגון|צער|ששון|כעס|געגוע
עלטה|אפלה|אורה|ערפל|סערה
איבה|שנאה|רעות|קנאה|גאווה
תבונה|בינה|איוולת|זיכרון|זהירות
שגשוג|פריחה|דעיכה|שינוי|מרוץ
כזב|שקר|אמת|סוד|אכזבה`;
  const bank = (s) => s.split("\n").map((l) => l.trim().split("|"));
  Games.register({
    id: "synonyms", cat: "language", name: "נרדפות והפכים", icon: "↔️",
    desc: "מילה באותה משמעות – או ההפך",
    how: `מופיעה מילה ושאלה: "מה ההפך?" או "מה המילה הנרדפת?" (אותה משמעות). בחרו את התשובה. ${ROUNDS} שאלות.<br>השאלות מעורבבות, ובין התשובות מסתתרת גם המשמעות השנייה – אז קראו היטב מה שואלים. ברמות גבוהות המילים ספרותיות יותר.`,
    start(stage, level, api) {
      const pool = level <= 8 ? bank(EVERYDAY) : level <= 20 ? bank(EVERYDAY + "\n" + LITERARY) : bank(LITERARY);
      const order = shuffle(pool).slice(0, ROUNDS);
      return runQuiz(stage, api, {
        rounds: ROUNDS, targetT: lerp(6, 8, level), accW: 80, optClass: "txt",
        make(i) {
          const w = order[(i - 1) % order.length];
          const mode = pick(["opp", "syn"]);
          const ans = mode === "opp" ? w[2] : w[1];
          const others = [mode === "opp" ? w[1] : w[2], w[3], w[4]];
          const q = mode === "opp" ? "מה ההפך של" : "מה המילה הנרדפת ל";
          return { html: `<div class="q-line">${q}</div><div class="big-q">${w[0]}</div>`, ans, opts: shuffle([ans, ...others]), prompt: mode === "opp" ? "⇄ הפך" : "＝ אותה משמעות" };
        }
      });
    }
  });
})();
